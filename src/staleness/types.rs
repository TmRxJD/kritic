//! One manifest owns canonical inputs, test review bindings and generated fixtures.
use std::collections::BTreeMap;

use schemars::JsonSchema;
use serde::{Deserialize, Serialize};

#[derive(Debug, Deserialize, JsonSchema)]
#[serde(deny_unknown_fields)]
pub struct Request {
    pub base_dir: String,
    /// Default .kritic/test-contracts.toml. Read-only; no tests, generators or models run.
    pub manifest_path: Option<String>,
}

#[derive(Debug, Deserialize, Serialize, JsonSchema)]
#[serde(deny_unknown_fields)]
pub struct Manifest {
    pub version: u32,
    /// Explicit corpus, relative directories. Nothing outside these roots is inventoried.
    pub test_roots: Vec<String>,
    /// Regex over repository-relative paths, with forward slashes. No implicit language parser.
    pub test_pattern: String,
    pub authorities: Vec<Authority>,
    pub tests: Vec<TestBinding>,
    #[serde(default)]
    pub generated: Vec<Generated>,
    #[serde(default)]
    pub exclusions: Vec<Exclusion>,
    #[serde(default)]
    pub boundaries: Vec<Boundary>,
    #[serde(default)]
    pub invariants: Vec<Invariant>,
}

#[derive(Debug, Deserialize, Serialize, JsonSchema)]
#[serde(deny_unknown_fields)]
pub struct Boundary {
    pub id: String,
    pub authority: String,
    pub risk: String,
    pub external_input: bool,
    pub required_in_release: bool,
    pub required_invariants: Vec<String>,
}

#[derive(Debug, Deserialize, Serialize, JsonSchema, PartialEq)]
#[serde(rename_all = "snake_case")]
pub enum GuardKind {
    RuntimeGuard,
    TypeConstraint,
    SchemaValidation,
    DebugAssertion,
}

#[derive(Debug, Deserialize, Serialize, JsonSchema, PartialEq)]
#[serde(rename_all = "snake_case")]
pub enum FailurePolicy {
    RejectError,
    PanicInternal,
}

#[derive(Debug, Deserialize, Serialize, JsonSchema)]
#[serde(deny_unknown_fields)]
pub struct Invariant {
    pub id: String,
    pub boundary: String,
    pub condition: String,
    pub rationale: String,
    pub guard_kind: GuardKind,
    pub failure_policy: FailurePolicy,
    pub enforcement_pattern: String,
    pub negative_tests: Vec<NegativeTest>,
}

#[derive(Debug, Deserialize, Serialize, JsonSchema)]
#[serde(deny_unknown_fields)]
pub struct NegativeTest {
    pub path: String,
    pub pattern: String,
    pub purpose: String,
}

#[derive(Debug, Serialize, JsonSchema)]
pub struct InvariantEvidence {
    pub id: String,
    pub boundary: String,
    pub condition: String,
    pub rationale: String,
    pub boundary_risk: String,
    pub external_input: bool,
    pub required_in_release: bool,
    pub failure_policy: String,
    pub enforcement_path: String,
    pub enforcement_line: Option<usize>,
    pub enforcement_excerpt: Option<String>,
    pub negative_test_paths: Vec<String>,
}

#[derive(Debug, Deserialize, Serialize, JsonSchema)]
#[serde(deny_unknown_fields)]
pub struct Authority {
    pub id: String,
    /// Unique logical domain: two files cannot both own the same domain.
    pub domain: String,
    pub path: String,
    pub owner: String,
    pub purpose: String,
}

#[derive(Debug, Deserialize, Serialize, JsonSchema)]
#[serde(deny_unknown_fields)]
pub struct TestBinding {
    pub path: String,
    pub purpose: String,
    /// Reviewer-approved exact test bytes, never automatically refreshed.
    pub reviewed_test_sha256: String,
    /// Authority ID -> reviewed SHA-256. Include relevant schemas, APIs, lockfiles/config.
    pub reviewed_inputs: BTreeMap<String, String>,
    /// Declared behavioral validation command, not executed by this critic.
    pub validation_command: String,
}

#[derive(Debug, Deserialize, Serialize, JsonSchema)]
#[serde(deny_unknown_fields)]
pub struct Generated {
    pub path: String,
    pub authority: String,
    /// JSON Pointer into an independent canonical JSON contract (empty selects root).
    pub pointer: String,
    pub purpose: String,
    /// Test paths that consume this fixture; each must bind its authority.
    pub consumers: Vec<String>,
}

#[derive(Debug, Deserialize, Serialize, JsonSchema)]
#[serde(deny_unknown_fields)]
pub struct Exclusion {
    pub path: String,
    pub reason: String,
}

#[derive(Debug, Serialize, JsonSchema)]
pub struct Finding {
    pub code: String,
    pub path: String,
    pub detail: String,
    pub action: String,
}

#[derive(Debug, Serialize, JsonSchema)]
pub struct Observed {
    pub path: String,
    pub sha256: String,
}

#[derive(Debug, Serialize, JsonSchema)]
pub struct Report {
    pub tool: String,
    pub base_dir: String,
    pub manifest_path: String,
    pub manifest_sha256: Option<String>,
    pub status: String,
    /// Only declared ownership, inventory, review hashes and generated bytes are checked.
    pub deterministic_ok: bool,
    /// Semantic currency and test execution are never established by hashing files.
    pub approval: Option<bool>,
    pub discovered_tests: usize,
    pub mapped_tests: usize,
    pub excluded_tests: usize,
    pub finding_count: usize,
    pub findings: Vec<Finding>,
    pub observed: Vec<Observed>,
    pub review_notes: Vec<String>,
    pub invariant_evidence: Vec<InvariantEvidence>,
    pub limitations: Vec<String>,
    pub setup: Vec<String>,
    pub full_result: Option<String>,
}

#[derive(Debug, Serialize, JsonSchema)]
pub struct SyncReport {
    pub written: Vec<String>,
    pub unchanged: Vec<String>,
    pub would_update: Vec<String>,
    pub review_required: bool,
    pub note: String,
}
