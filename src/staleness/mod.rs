mod sync;
mod types;

use std::path::Path;
pub use sync::sync;
pub use types::*;

pub const DEFAULT_MANIFEST: &str = ".kritic/test-contracts.toml";

pub fn check_invariants(base: &Path, path: Option<&str>) -> Result<Report, String> {
    let mut report = check(base, path)?;
    report.tool = "invariant_critic".into();
    if report.invariant_evidence.is_empty() {
        audit::finding(
            &mut report,
            "invariants_setup_required",
            path.unwrap_or(DEFAULT_MANIFEST),
            "No invariant evidence was available for declared key boundaries",
            "Declare boundaries and meaningful invariants in the same test-contract manifest; include release guards, failure policies and mapped negative tests. See docs/staleness.md.",
        );
        report.deterministic_ok = false;
        report.approval = Some(false);
        report.status = "setup_required".into();
        report.finding_count = report.findings.len();
    }
    Ok(report)
}

pub fn schema() -> serde_json::Value {
    serde_json::json!(schemars::schema_for!(Manifest))
}

pub fn execute(request: &Request) -> Result<Report, String> {
    check(
        Path::new(&request.base_dir),
        request.manifest_path.as_deref(),
    )
}

pub fn check(base: &Path, path: Option<&str>) -> Result<Report, String> {
    let base = base
        .canonicalize()
        .map_err(|e| format!("Staleness base_dir: {e}"))?;
    if !base.is_dir() {
        return Err("Staleness base_dir must be a directory".into());
    }
    let path = path.unwrap_or(DEFAULT_MANIFEST);
    let mut report = Report {
        tool: "staleness_critic".into(), base_dir: base.to_string_lossy().into_owned(), manifest_path: path.into(), manifest_sha256: None,
        status: "setup_required".into(), deterministic_ok: false, approval: None, discovered_tests: 0, mapped_tests: 0, excluded_tests: 0, finding_count: 0,
        findings: vec![], observed: vec![], review_notes: vec![], invariant_evidence: vec![], full_result: None,
        limitations: vec![
            "Only the explicit roots and path regex are inventoried; embedded/other-framework tests outside this corpus are unverified. Excluded generated/private trees are never scanned.".into(),
            "Review hashes are caller declarations, not execution or reviewer authentication. Same hashes cannot prove tests assert the intended behavior, are discovered by their runner, or are independent of implementation.".into(),
            "Canonical domain uniqueness and generated bytes are checked; actual ownership, complete dependency links and semantic contract/schema enforcement need independent review. No language/type/schema parser or test runner is executed.".into(),
            "Changed source/test hashes require review, not automatic expectation replacement. No test is deleted, skipped, blessed or rewritten by the critic.".into(),
        ],
        setup: vec![],
    };
    match manifest::load(&base, path) {
        Err(e) => {
            audit::finding(
                &mut report,
                "manifest_setup_required",
                path,
                e,
                "Use kritic staleness --schema and docs/staleness.md. Derive real canonical owners and test dependencies; never copy example hashes or auto-bless the current implementation.",
            );
            report.setup = vec!["Inventory actual test-runner inputs, including embedded tests and relevant dependency/config/schema contracts; define bounded test_roots and a test_pattern that includes them.".into(), "Declare one owner/source per canonical domain. Bind every discovered test to independently reviewed source and test SHA-256 values; preserve unknown coverage.".into(), "Declare only reproducible JSON fixtures and their real consumers. Use sync dry run, review, then sync --write; wire check into the repository's existing pre-test/CI command after review.".into()];
        }
        Ok((m, hash)) => {
            report.manifest_sha256 = Some(hash);
            audit::check(&base, path, &m, &mut report);
            invariants::check(&base, &m, &mut report);
            report.deterministic_ok = report.findings.is_empty();
            report.status = if report.deterministic_ok {
                "consistent"
            } else {
                "review_required"
            }
            .into();
        }
    }
    report.finding_count = report.findings.len();
    if !report.findings.is_empty() {
        report.approval = Some(false);
    }
    Ok(report)
}
